## الاستخدام المقبول
يُمنع: انتحال شخصية أو بيانات كاذبة، التلاعب بالأسعار أو الإيصالات أو النجوم، رفع إيصال مزور أو مكرر، إساءة معاملة العملاء أو السائقين أو التجار، محاولة اختراق الموقع أو تعطيله، واستخدام الخدمة في نشاط مخالف للقانون.

## التوصيل
