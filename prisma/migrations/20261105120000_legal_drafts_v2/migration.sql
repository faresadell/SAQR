## القبول
باستخدامك صقر أو إنشائك حساباً فيه فإنك توافق على هذه الشروط وعلى سياسة الخصوصية. إن لم توافق فلا تستخدم الخدمة.

## ما هي صقر
صقر منصة وسيطة تربط العملاء بالمطاعم والمحلات والسائقين. النشاط التجاري هو البائع ومسؤول عن منتجاته وأسعارها وجودتها ومواعيد عمله. دور المنصة هو التنظيم والتشغيل والمراجعة.

## الحساب
- يجب أن تكون بياناتك صحيحة، ويجب ألا يقل عمرك عن 18 عاماً.
- أنت مسؤول عن سرية كلمة المرور وعن كل ما يتم من حسابك.
- لكل شخص حساب واحد. لا يجوز التنازل عن الحساب أو بيعه.
- أنواع الحسابات: عميل، تاجر، سائق، إدارة. يعتمد التاجر قبل ظهور نشاطه للعملاء.

## الطلب
- تضيف منتجات من نشاط أو أكثر إلى سلة واحدة، وكل نشاط يُنفَّذ كطلب فرعي مستقل له حالته.
- السعر النهائي يحدده الخادم عند التأكيد. إن تغير سعر منتج قبل التأكيد فسننبهك.
- رسوم التوصيل تُحدد حسب منطقة عنوانك لكل طلب فرعي، وتُدفع نقداً للسائق عند التسليم.
- يقبل التاجر الطلب أو يرفضه، وللعميل متابعة كل خطوة.

## الدفع
- الدفع حالياً بتحويل يدوي إلى الرقم المعروض (فودافون كاش أو إنستاباي) ثم رفع إيصال ورقم مرجعي للتحويل.
- لا يُقبل استخدام نفس الرقم المرجعي لأكثر من عملية.
- يؤكد النشاط استلام التحويل، وتراجع الإدارة العمليات عند الحاجة.
- لا نخزّن بيانات بطاقات بنكية.

## النجوم
- النجوم رصيد داخل المنصة يُشترى بتحويل يدوي وتعتمده الإدارة قبل إضافته إلى حسابك.
- يُخصم من العميل ومن النشاط عدد من النجوم (حالياً نجمتان من كل طرف) عند موافقة النشاط على كل طلب فرعي، ويُرد مرة واحدة عند الإلغاء بعد الخصم.
- تحدد الإدارة عدد النجوم والأسعار وقد تعدلها مستقبلاً دون أثر على الطلبات السابقة.

## عمولة المنصة
تُحسب عمولة المنصة من النشاط على قيمة المنتجات بعد الخصم فقط، دون رسوم التوصيل: 8% للحساب العادي و5% لحساب بريميوم. تُسجَّل النسبة وقت الطلب ولا تتأثر بتغييرها لاحقاً.

## الإلغاء والاسترجاع
