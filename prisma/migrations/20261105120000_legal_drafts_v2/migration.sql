## من نحن
صقر (SAQR) منصة تجمع العملاء والمطاعم والمحلات والسائقين في مكان واحد داخل مصر. تشرح هذه السياسة ما هي البيانات التي نجمعها عنك، ولماذا، ومن يراها، وكيف نحميها، وما هي حقوقك.

## البيانات التي نجمعها
- بيانات الحساب: الاسم، رقم الموبايل (للتواصل ولا نتحقق منه برسالة)، البريد الإلكتروني (لتفعيل الحساب واستعادة كلمة المرور)، وكلمة المرور (نخزنها بصيغة مشفرة لا يمكن قراءتها).
- العناوين: عنوان التوصيل الذي تكتبه، وإحداثيات الموقع إن وُجدت.
- الطلبات: ما طلبته وأسعاره والنشاط الذي طلبت منه وحالة الطلب والسائق المسند.
- الدفع: صورة إيصال التحويل والرقم المرجعي للتحويل الذي ترفعه. نحن لا نجمع ولا نخزن بيانات بطاقات بنكية.
- بيانات التاجر: اسم النشاط وعنوانه وأرقامه وصوره ومنتجاته وأسعارها.
- الشكاوى والإشعارات: نص الشكوى وردنا عليها، والإشعارات التي أُرسلت إليك.
- بيانات تقنية للأمان: عنوان الاتصال (IP) ونوع الجهاز والمتصفح عند تسجيل الدخول، وسجل للعمليات الإدارية، وعدّادات لمنع المحاولات المتكررة.

## ملفات تعريف الارتباط والتخزين على جهازك
- نستخدم ملف تعريف ارتباط واحداً أساسياً لإبقائك مسجلاً للدخول، ولا يعمل الدخول بدونه.
- نحفظ على جهازك محتوى سلة الطلبات وتفضيل صوت الافتتاح.
- لا نستخدم ملفات تتبع إعلانية ولا أدوات تحليل سلوك الزوار.

## لماذا نستخدم بياناتك
- لإنشاء حسابك وتشغيله وحمايته.
- لتنفيذ طلباتك: إيصالها للنشاط واختيار سائق وتوصيلها وتحصيل رسوم التوصيل.
- لمراجعة الدفع اليدوي والاسترجاع وحل الشكاوى.
- لإرسال رسائل الخدمة (رمز التفعيل واستعادة كلمة المرور وحالة الطلب).
- لمنع الاحتيال والاستخدام المسيء والالتزام بالقانون.
لا نبيع بياناتك، ولا نستخدمها للإعلانات.

## من يطلع على بياناتك
- النشاط الذي طلبت منه: اسمك ورقمك وعنوان التوصيل وتفاصيل طلبك.
- السائق: لا يرى عنوانك قبل قبوله للطلب. بعد القبول يرى الاسم والرقم والعنوان اللازمين للتوصيل.
- إدارة المنصة: بالقدر اللازم لمراجعة الدفع والشكاوى والدعم والأمان، وكل إجراء إداري يُسجَّل.
- صور إيصالات الدفع: لا يطلع عليها إلا صاحب الطلب والنشاط المعني وإداري مخوّل.
- جهات أخرى: عند طلب رسمي من جهة مختصة وفق القانون.

## مزودو الخدمات التقنية
نستعين بشركات تقنية لتشغيل الموقع نيابة عنا، وهي: استضافة الموقع، وقاعدة البيانات، وتخزين الصور والإيصالات، وإرسال البريد الإلكتروني، والحماية من البرامج الآلية. تعالج هذه الجهات البيانات اللازمة لعملها فقط، وقد تقع خوادمها خارج مصر. نختار جهات توفر حماية مناسبة للبيانات وفق القانون.

## الدفع
الدفع حالياً بتحويل يدوي (فودافون كاش أو إنستاباي) ثم رفع إيصال ومراجعته. عملية التحويل نفسها تتم داخل تطبيق مزود الدفع وتخضع لسياسته.

## مدة الاحتفاظ
نحتفظ ببيانات حسابك طالما حسابك قائم. وقد نحتفظ بسجلات الطلبات والمدفوعات والاسترجاع والإجراءات الإدارية المدة اللازمة للمحاسبة وحل النزاعات ومنع الاحتيال والالتزام بالقانون.

## أمان بياناتك
- كلمات المرور مشفرة، والأسرار الحساسة محفوظة بتشفير.
- الاتصال بالموقع مؤمّن، والصور والإيصالات في تخزين خاص لا يُفتح إلا عبر صلاحية.
- حسابات الإدارة تحتاج رمز مصادقة إضافياً.
- نحدّ من محاولات الدخول المتكررة.
لا يوجد نظام آمن بنسبة مئة بالمئة. إن اكتشفنا اختراقاً يمس بياناتك فسنتصرف وفق القانون ونبلغ المتضررين بما يلزم.

## حقوقك
وفق قانون حماية البيانات الشخصية المصري رقم 151 لسنة 2020 يحق لك:
- معرفة بياناتك التي نحتفظ بها والاطلاع عليها.
- تصحيح بياناتك. تستطيع تعديل اسمك ورقمك من صفحة حسابك.
- طلب حذف بياناتك، مع مراعاة ما يلزمنا الاحتفاظ به قانوناً.
- الاعتراض على معالجة بياناتك أو تقييدها.
- طلب نسخة من بياناتك.
لتقديم أي طلب استخدم وسائل التواصل الرسمية في صفحة الدعم. لا يوجد حالياً زر لحذف الحساب داخل الموقع، ويتم الحذف بطلب عبر الدعم.

