// Decides what a file REALLY is from its first bytes. The client's file name and Content-Type are never trusted.
export const MAX_RECEIPT_BYTES = 5 * 1024 * 1024;

export type ImageKind = { contentType: "image/jpeg" | "image/png" | "image/webp"; ext: "jpg" | "png" | "webp" };

const startsWith = (b: Uint8Array, sig: number[], at = 0) => sig.every((v, i) => b[at + i] === v);

export function detectImage(bytes: Uint8Array): ImageKind | null {
  if (bytes.length < 16) return null;
  if (startsWith(bytes, [0xff, 0xd8, 0xff])) return { contentType: "image/jpeg", ext: "jpg" };
  if (startsWith(bytes, [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) return { contentType: "image/png", ext: "png" };
  // WebP: "RIFF" <size> "WEBP"
  if (startsWith(bytes, [0x52, 0x49, 0x46, 0x46]) && startsWith(bytes, [0x57, 0x45, 0x42, 0x50], 8)) return { contentType: "image/webp", ext: "webp" };
  return null;
}

/**
 * A JPEG taken by a phone carries EXIF (often GPS coordinates), XMP, IPTC and comments. The app re-encodes pictures in the browser, but a
 * direct upload keeps them, and the picture then reaches a shop or a driver. This drops those segments and keeps everything the picture needs
 * (including the colour profile). Anything that does not parse cleanly is returned untouched. PNG and WebP are left as they are.
 */
export function stripImageMetadata(bytes: Uint8Array, kind: ImageKind): Uint8Array {
  if (kind.contentType !== "image/jpeg") return bytes;
  const out: number[] = [0xff, 0xd8];
  let i = 2;
  while (i + 3 < bytes.length) {
    if (bytes[i] !== 0xff) return bytes;
    const marker = bytes[i + 1]!;
    if (marker === 0xff) { i += 1; continue; } // fill byte
    if (marker === 0xd9) { out.push(0xff, 0xd9); i += 2; break; }
    if (marker === 0xda) { // start of scan: the rest is compressed data
      for (let j = i; j < bytes.length; j++) out.push(bytes[j]!);
      return Uint8Array.from(out);
    }
    if (marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { out.push(0xff, marker); i += 2; continue; }
    const length = (bytes[i + 2]! << 8) | bytes[i + 3]!;
    if (length < 2 || i + 2 + length > bytes.length) return bytes;
    const drop = marker === 0xe1 || marker === 0xed || marker === 0xfe; // APP1 (EXIF/XMP), APP13 (IPTC), comment
    if (!drop) for (let j = i; j < i + 2 + length; j++) out.push(bytes[j]!);
    i += 2 + length;
  }
  return Uint8Array.from(out);
}

/** Keys are generated by the server only; this guards reads/writes against path traversal. */
export const STORAGE_KEY_PATTERN = /^(receipts|product-images|shop-images|chat-images|offer-images)\/[A-Za-z0-9]{8,40}\/[a-f0-9-]{36}\.(jpg|png|webp)$/;
