// Decides what a file REALLY is from its first bytes. The client's file name and Content-Type are never trusted.
export const MAX_RECEIPT_BYTES = 5 * 1024 * 1024;

export type ImageKind = { contentType: "image/jpeg" | "image/png" | "image/webp"; ext: "jpg" | "png" | "webp" };

const startsWith = (b: Uint8Array, sig: number[], at = 0) => sig.every((v, i) => b[at + i] === v);

export function detectImage(bytes: Uint8Array): ImageKind | null {
  if (bytes.length < 16) return null;
  if (startsWith(bytes, [0xff, 0xd8, 0xff])) return { contentType: "image/jpeg", ext: "jpg" };
  if (startsWith(bytes, [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) return { contentType: "image/png", ext: "png" };
  // WebP: "RIFF" <size> "WEBP"
  if (startsWith(bytes, [0x52, 0x49, 0x46, 0x46]) && startsWith(bytes, [0x57, 0x45, 0x42, 0x50], 8)) return { contentType: "image/webp", ext: "webp" };
  return null;
}

/** Keys are generated by the server only; this guards reads/writes against path traversal. */
export const STORAGE_KEY_PATTERN = /^(receipts|product-images)\/[A-Za-z0-9]{8,40}\/[a-f0-9-]{36}\.(jpg|png|webp)$/;
